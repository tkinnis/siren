    '#8040a0',
    '#208050',
    '#c07000',
    '#e45756',
    '#4c78a8',
    '#b279a2',
  ],
);

const pele.PelePalette _darkMermaidPalette = pele.PelePalette(
  bg: '#141424',
  fg: '#e0e0f0',
  fgOnLight: '#1a1a2e',
  fgOnDark: '#e0e0f0',
  muted: '#9898b8',
  line: '#c8c8e0',
  surface: '#1e1e30',
  surfaceAlt: '#25253e',
  border: '#5c5c84',
  accent: '#00d4aa',
  code: '#25253e',
  critical: '#f87171',
  colors: <String>[
    '#6bb8ff',
    '#00d4aa',
    '#b86bff',
    '#6bffb8',
    '#ffb86b',
    '#f87171',
    '#72b7b2',
    '#f5c2e7',
  ],
);

void main() {
  final docsDir = Directory('docs');
  if (!docsDir.existsSync()) {
    stderr.writeln('Error: docs/ directory not found.');
    exit(1);
  }

  final fenceRegex = RegExp(
    r'^```mermaid[ \t]*\r?\n([\s\S]*?)^```[ \t]*$',
    multiLine: true,
  );

  final Map<String, Map<String, String>> diagrams =
      <String, Map<String, String>>{};
  int totalBlocks = 0;

  final mdFiles =
      docsDir
          .listSync()
          .whereType<File>()
          .where((f) => f.path.endsWith('.md'))
          .toList()
        ..sort((a, b) => a.path.compareTo(b.path));

  for (final file in mdFiles) {
    final content = file.readAsStringSync();
    for (final match in fenceRegex.allMatches(content)) {
      final code = (match.group(1) ?? '').trim();
      if (code.isEmpty || diagrams.containsKey(code)) continue;
      totalBlocks++;

      final lightRendered = pele.render(
        code,
        const pele.RenderOptions(
          outputMode: pele.SvgOutputMode.flattened,
          palette: _lightMermaidPalette,
        ),
      );
      final darkRendered = pele.render(
        code,
        const pele.RenderOptions(
          outputMode: pele.SvgOutputMode.flattened,
          palette: _darkMermaidPalette,
        ),
      );

      diagrams[code] = <String, String>{
        'light': lightRendered.svg,
        'dark': darkRendered.svg,
      };
    }
  }

  final outJs = File('docs/pele_diagrams.js');
  final jsonPayload = const JsonEncoder().convert(diagrams);
  outJs.writeAsStringSync(
    '// Generated by tool/generate_docs_diagrams.dart — DO NOT EDIT MANUALLY\n'
    'window.SIREN_PELE_DIAGRAMS = $jsonPayload;\n',
  );

  stdout.writeln(
    'Generated docs/pele_diagrams.js with $totalBlocks unique pele_dart diagrams (Light & Dark SVGs).',
  );
}
