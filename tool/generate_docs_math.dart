import 'dart:convert';
import 'dart:io';
import 'dart:isolate';

import 'package:tex_math/tex_math.dart';

const Map<TexMathColorRole, String> _lightMathColors =
    <TexMathColorRole, String>{
      TexMathColorRole.foreground: '#1a1a2e',
      TexMathColorRole.accent: '#00a080',
      TexMathColorRole.error: '#dc2626',
      TexMathColorRole.muted: '#5a5a78',
    };

const Map<TexMathColorRole, String> _darkMathColors =
    <TexMathColorRole, String>{
      TexMathColorRole.foreground: '#e0e0f0',
      TexMathColorRole.accent: '#00d4aa',
      TexMathColorRole.error: '#f87171',
      TexMathColorRole.muted: '#9898b8',
    };

String _maskNonProse(String markdown) {
  var content = markdown.replaceFirst(
    RegExp(r'^---\r?\n[\s\S]*?\r?\n---\r?\n'),
    '',
  );
  content = content.replaceAllMapped(
    RegExp(r'(`{3,}|~{3,})[\s\S]*?\1'),
    (m) => ' ' * m.group(0)!.length,
  );
  content = content.replaceAllMapped(
    RegExp(r'`[^`\n]+`'),
    (m) => ' ' * m.group(0)!.length,
  );
  return content;
}

Future<void> main() async {
  final docsDir = Directory('docs');
  if (!docsDir.existsSync()) {
    stderr.writeln('Error: docs/ directory not found.');
    exit(1);
  }

  final flutterPkgUri = await Isolate.resolvePackageUri(
    Uri.parse('package:tex_math_flutter/tex_math_flutter.dart'),
  );
  if (flutterPkgUri == null) {
    stderr.writeln('Error: unable to resolve package:tex_math_flutter URI.');
    exit(1);
  }

  final fontFile = File.fromUri(
    flutterPkgUri.resolve('../assets/fonts/NewCMMath-Regular.otf'),
  );
  if (!fontFile.existsSync()) {
    stderr.writeln('Error: bundled NewCMMath-Regular.otf not found.');
    exit(1);
  }

  final font = MathFont.fromBytes(fontFile.readAsBytesSync());
  final engine = TexMathEngine(font: font);

  final displayRegex = RegExp(r'\$\$([\s\S]+?)\$\$');
  final inlineRegex = RegExp(r'\$([^\$\n]+?)\$');

  final Map<String, Map<String, Object>> renderedMath =
      <String, Map<String, Object>>{};
  int renderedCount = 0;
  int errorCount = 0;

  void addExpression(String tex, {required bool isBlock}) {
    final trimmed = tex.trim();
    if (trimmed.isEmpty) return;
    final key = '${isBlock ? 'block' : 'inline'}:$trimmed';
    if (renderedMath.containsKey(key)) return;

    final options = TexMathOptions(
      displayMode: isBlock
          ? TexMathDisplayMode.display
          : TexMathDisplayMode.inline,
    );
    final fontSize = isBlock ? 18.0 : 16.0;

    try {
      final result = engine.render(trimmed, options: options);
      final lightSvg = result.toSvg(
        fontSize: fontSize,
        colors: _lightMathColors,
      );
      final darkSvg = result.toSvg(fontSize: fontSize, colors: _darkMathColors);
      final depthEm = double.parse(
        result.displayList.metrics.depthEm.toStringAsFixed(4),
      );
      renderedMath[key] = <String, Object>{
        'light': lightSvg,
        'dark': darkSvg,
        'depthEm': depthEm,
      };
      renderedCount++;
    } on TexMathError catch (error) {
      renderedMath[key] = <String, Object>{
        'error': error.formattedMessage,
        'source': trimmed,
      };
      errorCount++;
    }
  }

  final mdFiles =
      docsDir
          .listSync()
          .whereType<File>()
          .where((f) => f.path.endsWith('.md'))
          .toList()
        ..sort((a, b) => a.path.compareTo(b.path));

  for (final file in mdFiles) {
    final masked = _maskNonProse(file.readAsStringSync());
    final withoutDisplay = masked.replaceAllMapped(displayRegex, (match) {
      addExpression(match.group(1) ?? '', isBlock: true);
      return ' ' * match.group(0)!.length;
    });
    for (final match in inlineRegex.allMatches(withoutDisplay)) {
      addExpression(match.group(1) ?? '', isBlock: false);
    }
  }

  final outJs = File('docs/tex_math_svgs.js');
  final jsonPayload = const JsonEncoder().convert(renderedMath);
  outJs.writeAsStringSync(
    '// Generated by tool/generate_docs_math.dart — DO NOT EDIT MANUALLY\n'
    'window.SIREN_TEX_MATH_SVGS = $jsonPayload;\n',
  );

  stdout.writeln(
    'Generated docs/tex_math_svgs.js with $renderedCount rendered formulas and $errorCount intentional error entries (Light & Dark SVGs).',
  );
}
